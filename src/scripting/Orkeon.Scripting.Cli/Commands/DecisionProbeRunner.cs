/// <summary>
/// Runs the decision modes (D1–D7) against a live decision provider — TypeSafe (Jev), Liquid
/// or Kev — behind <c>orkeon llm probe -p typesafe</c>.
/// </summary>
/// <remarks>
/// <para>
/// A decision model answers typed questions about a state; it does not chat, stream or call
/// tools, so none of M1–M13 applies to it. The D modes are its own protocol, reported in the
/// same JSON as the chat modes so the campaign kit archives and indexes it unchanged.
/// </para>
/// <para>
/// Each question has an obvious answer, so a mode checks what the model said and not only that
/// it said something: an answer of the right type but the wrong value is a red the shape alone
/// would never show.
/// </para>
/// </remarks>
internal sealed class DecisionProbeRunner
{
