    /// <summary>Where the digits sit in <see cref="DecisionProbeImagePng"/>, as fractions: pixels 92–228 × 118–202.</summary>
    internal static readonly BoxCoordinates ExpectedBox = new()
    {
        Top = 118 / 320.0,
        Bottom = 202 / 320.0,
        Left = 92 / 320.0,
        Right = 228 / 320.0,
    };

    private readonly IDecisionModel _model;

    /// <summary>Initializes a new runner over an already-configured decision model.</summary>
    /// <param name="model">The decision model under test.</param>
    public DecisionProbeRunner(IDecisionModel model)
    {
        ArgumentNullException.ThrowIfNull(model);
        _model = model;
    }

    /// <summary>
    /// Gets whether the provider takes images and <c>box</c> questions; when false D4 is not
    /// applicable. Kev, and d1 served by llama.cpp, take only noul, choice and score questions.
    /// </summary>
    public bool SupportsBox { get; init; } = true;

    /// <summary>Gets the modes this runner exercises, in protocol order.</summary>
    public static IReadOnlyList<LlmProbeMode> SupportedModes { get; } =
    [
        LlmProbeMode.D1, LlmProbeMode.D2, LlmProbeMode.D3, LlmProbeMode.D4,
        LlmProbeMode.D5, LlmProbeMode.D6, LlmProbeMode.D7,
    ];

    /// <summary>Runs the requested modes in order and returns one result per mode.</summary>
    /// <param name="modes">The modes to exercise.</param>
    /// <param name="cancellationToken">Cancels the whole campaign.</param>
    /// <returns>One result per requested mode, in the order requested.</returns>
    public async Task<IReadOnlyList<LlmProbeResult>> RunAsync(
        IEnumerable<LlmProbeMode> modes, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(modes);

        var results = new List<LlmProbeResult>();
        foreach (var mode in modes)
        {
            cancellationToken.ThrowIfCancellationRequested();
            results.Add(await RunOneAsync(mode, cancellationToken).ConfigureAwait(false));
        }

        return results;
    }

    private async Task<LlmProbeResult> RunOneAsync(LlmProbeMode mode, CancellationToken cancellationToken)
    {
        var stopwatch = Stopwatch.StartNew();
        try
        {
            var (outcome, detail) = await DispatchAsync(mode, cancellationToken).ConfigureAwait(false);
            return new LlmProbeResult(mode, outcome, detail, stopwatch.ElapsedMilliseconds);
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            throw;
        }
#pragma warning disable CA1031 // A probe reports every failure as a failed mode; one bad mode must not abort the campaign.
        catch (Exception ex)
#pragma warning restore CA1031
        {
            return new LlmProbeResult(
                mode, LlmProbeOutcome.Failed, $"threw {ex.GetType().Name}: {ex.Message}",
                stopwatch.ElapsedMilliseconds);
        }
    }

    private Task<(LlmProbeOutcome Outcome, string Detail)> DispatchAsync(
        LlmProbeMode mode, CancellationToken cancellationToken) => mode switch
        {
            LlmProbeMode.D1 => ProbeNoulAsync(cancellationToken),
            LlmProbeMode.D2 => ProbeChoiceAsync(cancellationToken),
            LlmProbeMode.D3 => ProbeScoreAsync(cancellationToken),
            LlmProbeMode.D4 => ProbeBoxAsync(cancellationToken),
            LlmProbeMode.D5 => ProbeContextLimitAsync(cancellationToken),
            LlmProbeMode.D6 => ProbeErrorHandlingAsync(cancellationToken),
            LlmProbeMode.D7 => ProbeCancellationAsync(cancellationToken),
            _ => Task.FromResult((LlmProbeOutcome.Failed, $"mode {mode} is not a decision mode")),
        };

    // D1: a noul with instructions and criteria; the answer is a probability leaning yes.
    private async Task<(LlmProbeOutcome, string)> ProbeNoulAsync(CancellationToken cancellationToken)
    {
        var response = await DecideAsync(
            "refund",
            new NoulQuestion
            {
                Instructions = JsonValue.Create("Does the customer ask for a refund?"),
                Criteria = new NoulCriteria
                {
                    True = JsonValue.Create("The customer wants their money back."),
                    False = JsonValue.Create("The customer wants something else."),
                },
            },
            cancellationToken).ConfigureAwait(false);

        var noul = response.Get<NoulAnswer>("refund").Noul;
        var passed = noul is >= 0.5 and <= 1.0 && response.Usage.InputTokens > 0;
        return (Verdict(passed), $"noul={Format(noul)} (expected ≥ 0.5), {Usage(response)}");
    }

    // D2: a choice of three options; the delivery option is the obvious one.
    private async Task<(LlmProbeOutcome, string)> ProbeChoiceAsync(CancellationToken cancellationToken)
    {
        var response = await DecideAsync(
            "topic",
            new ChoiceQuestion
            {
                Instructions = JsonValue.Create("What is the customer's message about?"),
                Criteria = ImmutableDictionary<string, JsonNode?>.Empty
                    .Add("delivery", JsonValue.Create("A delivery problem"))
                    .Add("billing", JsonValue.Create("A billing question"))
                    .Add("account", JsonValue.Create("An account or login issue")),
            },
            cancellationToken).ConfigureAwait(false);

        var answer = response.Get<ChoiceAnswer>("topic");
        var sum = answer.Probabilities.Values.Sum();
        var passed = answer.Choice == "delivery" && Math.Abs(sum - 1.0) < 0.05;
        return (Verdict(passed),
            $"choice={answer.Choice} (expected delivery), confidence={Format(answer.Confidence)}, Σp={Format(sum)}, {Usage(response)}");
    }

    // D3: a three-level score; the angry message sits at the top of the scale.
    private async Task<(LlmProbeOutcome, string)> ProbeScoreAsync(CancellationToken cancellationToken)
    {
        var response = await DecideAsync(
            "urgency",
            new ScoreQuestion
            {
                Instructions = JsonValue.Create("How urgent is the customer's request?"),
                Criteria =
                [
                    JsonValue.Create("Not urgent: a general question.")!,
                    JsonValue.Create("Somewhat urgent: an inconvenience.")!,
                    JsonValue.Create("Urgent: money or goods were lost.")!,
                ],
            },
            cancellationToken).ConfigureAwait(false);

        var answer = response.Get<ScoreAnswer>("urgency");
        var passed = answer.Score is >= 1.0 and <= 2.0 && answer.Probabilities.Count > 0;
        return (Verdict(passed),
            $"score={Format(answer.Score)} on 0–2 (expected ≥ 1), confidence={Format(answer.Confidence)}, {Usage(response)}");
    }

    // D4: a box around the number painted on the probe image; it must touch where the digits are.
    private async Task<(LlmProbeOutcome, string)> ProbeBoxAsync(CancellationToken cancellationToken)
    {
        if (!SupportsBox)
            return (LlmProbeOutcome.NotApplicable, "the provider takes no image or box question");

        var request = new DecisionRequest
        {
            State = new JsonObject { ["photo"] = ProbeImageId },
            Assets = ImmutableDictionary<string, DecisionImage>.Empty.Add(
                ProbeImageId,
                new DecisionImage { Format = "png", DataBase64 = DecisionProbeImagePng }),
            Questions = ImmutableDictionary<string, DecisionQuestion>.Empty.Add(
                "number",
                new BoxQuestion { Instructions = JsonValue.Create("the number painted in `photo`") }),
        };

        var response = await _model.DecideAsync(request, cancellationToken).ConfigureAwait(false);
        var box = response.Get<BoxAnswer>("number").Box;
        // The box must touch the digits and not be the whole image — an image that never
        // arrived cannot do both. Its accuracy is the model's, reported and not judged:
        // TypeSafe calls Box "dreamer-ready", and Jev 1.14 drew it 0.1–0.15 too low, varying
        // from one call to the next (2026-11-11).
        var overlap = IntersectionOverUnion(box, ExpectedBox);
        var area = (box.Right - box.Left) * (box.Bottom - box.Top);
        var passed = box.Top < box.Bottom && box.Left < box.Right && overlap > 0 && area < 0.9;
        return (Verdict(passed),
            $"box top={Format(box.Top)} bottom={Format(box.Bottom)} left={Format(box.Left)} right={Format(box.Right)}, " +
            $"IoU={Format(overlap)} with the digits, {Usage(response)}");
    }

    // D5: a state far over the standard context is refused with a non-transient 4xx that names the limit.
    private async Task<(LlmProbeOutcome, string)> ProbeContextLimitAsync(CancellationToken cancellationToken)
    {
        // About 100k tokens of varied words: over the 64k standard context, under long context.
        string[] words = ["parcel", "invoice", "refund", "delivery", "account", "support", "ticket", "order"];
        var state = string.Join(' ', Enumerable.Range(0, 100_000).Select(i => words[i % words.Length] + i.ToString(CultureInfo.InvariantCulture)));
        var request = new DecisionRequest
        {
            State = JsonValue.Create(state),
            Questions = ImmutableDictionary<string, DecisionQuestion>.Empty.Add(
                "refund", new NoulQuestion { Instructions = JsonValue.Create("Does the text mention a refund?") }),
        };

        try
        {
            var response = await _model.DecideAsync(request, cancellationToken).ConfigureAwait(false);
            return (LlmProbeOutcome.Failed, $"an oversized state was answered ({Usage(response)})");
        }
        catch (DecisionModelException ex)
        {
            var named = ex.Message.Contains(
                $"context limit ({DecisionLimits.StandardContextTokens} tokens)", StringComparison.Ordinal);
            var passed = ex.StatusCode is >= 400 and < 500 && !ex.IsTransient && named;
            return (Verdict(passed), $"HTTP {ex.StatusCode}, transient={ex.IsTransient}: {Truncate(ex.Message)}");
        }
    }

    // D6: a model no provider serves is a typed, non-transient error — never a retry loop.
    private async Task<(LlmProbeOutcome, string)> ProbeErrorHandlingAsync(CancellationToken cancellationToken)
    {
        var request = Request("refund", new NoulQuestion { Instructions = JsonValue.Create("Does the customer ask for a refund?") })
            with { Model = NonexistentModel };
        try
        {
            var response = await _model.DecideAsync(request, cancellationToken).ConfigureAwait(false);
            return (LlmProbeOutcome.Failed, $"no error for an invalid model (served by {response.Model})");
        }
        catch (DecisionModelException ex)
        {
            var passed = ex.StatusCode is >= 400 and < 500 && !ex.IsTransient;
            return (Verdict(passed), $"HTTP {ex.StatusCode}, transient={ex.IsTransient}: {Truncate(ex.Message)}");
        }
    }

    // D7: a cancelled call stops promptly.
    private async Task<(LlmProbeOutcome, string)> ProbeCancellationAsync(CancellationToken cancellationToken)
    {
        using var linked = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        linked.CancelAfter(TimeSpan.FromMilliseconds(50));
        var stopwatch = Stopwatch.StartNew();
        try
        {
            await _model.DecideAsync(
                Request("refund", new NoulQuestion { Instructions = JsonValue.Create("Does the customer ask for a refund?") }),
                linked.Token).ConfigureAwait(false);
            return (LlmProbeOutcome.Failed, $"completed despite cancellation after {stopwatch.ElapsedMilliseconds} ms");
        }
        catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
        {
            return (LlmProbeOutcome.Passed, $"cancelled after {stopwatch.ElapsedMilliseconds} ms");
        }
    }

    // ── Shared helpers ──────────────────────────────────────────────────────

    private Task<DecisionResponse> DecideAsync(string name, DecisionQuestion question, CancellationToken cancellationToken)
        => _model.DecideAsync(Request(name, question), cancellationToken);

    private static DecisionRequest Request(string name, DecisionQuestion question) => new()
    {
        State = JsonValue.Create(ProbeState),
        Questions = ImmutableDictionary<string, DecisionQuestion>.Empty.Add(name, question),
    };

    internal static double IntersectionOverUnion(BoxCoordinates a, BoxCoordinates b)
    {
        var width = Math.Max(0, Math.Min(a.Right, b.Right) - Math.Max(a.Left, b.Left));
        var height = Math.Max(0, Math.Min(a.Bottom, b.Bottom) - Math.Max(a.Top, b.Top));
        var intersection = width * height;
        var union = ((a.Right - a.Left) * (a.Bottom - a.Top)) + ((b.Right - b.Left) * (b.Bottom - b.Top)) - intersection;
        return union <= 0 ? 0 : intersection / union;
    }

    private static LlmProbeOutcome Verdict(bool passed) =>
        passed ? LlmProbeOutcome.Passed : LlmProbeOutcome.Failed;

    private static string Format(double value) => value.ToString("0.###", CultureInfo.InvariantCulture);

    private static string Usage(DecisionResponse response) =>
        $"model={response.Model}, tokens in={response.Usage.InputTokens?.ToString(CultureInfo.InvariantCulture) ?? "?"}";

    private static string Truncate(string text) => text.Length <= 200 ? text : text[..200] + "…";
}
