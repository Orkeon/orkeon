using System.Diagnostics.CodeAnalysis;
using System.Windows;
using System.Windows.Controls;
using Orkeon.Studio.Wpf.ViewModels.Capture;
using Orkeon.Studio.Wpf.ViewModels.Shell;
using Orkeon.Studio.Wpf.Views;

namespace Orkeon.Studio.Wpf.Services.Capture;

/// <summary>
/// The whole WPF half of the campaign's vocabulary: which radio button a screen is, where the
/// splash lives, how the tour opens, and what "settled" means.
/// <para>
/// Everything else — what to arrange, why, and what to assert about it — lives in the catalogue,
/// which compiles into the net10.0 test assembly and is checked on Linux. This class is the part
/// that cannot be, and it is deliberately the only one.
/// </para>
/// </summary>
internal sealed class WpfCaptureSurface(MainWindow window, MainWindowViewModel shell) : ICaptureSurface
{
    /// <summary>The window this surface drives, for the executor's own rendering.</summary>
    [SuppressMessage("Minor Code Smell", "S3604:Member initializer values should not be redundant",
        Justification = "False positive on a primary constructor: the initializer IS the only "
                      + "assignment of the member, and removing it would leave it unset.")]
    public MainWindow Window { get; } = window;

    /// <inheritdoc />
    public async Task ShowAsync(CaptureScreen screen)
    {
        switch (screen)
        {
            case CaptureScreen.Create: Window.NavCreate.IsChecked = true; break;
            case CaptureScreen.Teams: Window.NavTeams.IsChecked = true; break;
            case CaptureScreen.Import: Window.NavImport.IsChecked = true; break;
            // Since the merge (refonte, lot 4) the trial is the Launch screen in trial mode.
            case CaptureScreen.Test: shell.Run.IsTrial = true; Window.NavRun.IsChecked = true; break;
            case CaptureScreen.Run: shell.Run.IsTrial = false; Window.NavRun.IsChecked = true; break;
            case CaptureScreen.History: Window.NavHistory.IsChecked = true; break;
            case CaptureScreen.Diagnostic: Window.NavDiag.IsChecked = true; break;

            case CaptureScreen.SettingsModel: ShowSettings(shell.Settings.ShowModelCommand); break;
            case CaptureScreen.SettingsRag: ShowSettings(shell.Settings.ShowRagCommand); break;
            case CaptureScreen.SettingsKeys: ShowSettings(shell.Settings.ShowKeysCommand); break;
            case CaptureScreen.SettingsFolders: ShowSettings(shell.Settings.ShowFoldersCommand); break;
            case CaptureScreen.SettingsLimits: ShowSettings(shell.Settings.ShowLimitsCommand); break;
            case CaptureScreen.SettingsJson: ShowSettings(shell.Settings.ShowJsonCommand); break;
            case CaptureScreen.SettingsTools: ShowSettings(shell.Settings.ShowToolsCommand); break;
            case CaptureScreen.SettingsToolKeys: ShowSettings(shell.Settings.ShowToolKeysCommand); break;
            case CaptureScreen.SettingsShell: ShowSettings(shell.Settings.ShowShellCommand); break;
            case CaptureScreen.SettingsEmail: ShowSettings(shell.Settings.ShowMailsCommand); break;
            case CaptureScreen.SettingsDrive: ShowSettings(shell.Settings.ShowDriveCommand); break;
            case CaptureScreen.SettingsMcp: ShowSettings(shell.Settings.ShowMcpCommand); break;
            case CaptureScreen.SettingsStudio: ShowSettings(shell.Settings.ShowStudioCommand); break;

            default: throw new ArgumentOutOfRangeException(nameof(screen), screen, "unknown capture screen");
        }

        // Every stop starts at the top of its screen, whatever the one before scrolled to: a
        // stop that brought a row into view, or a selection the app brought up in a teardown,
        // would otherwise decide where the next picture stands. The panel sits in the page host
        // (R01), so its scroll viewer is an ancestor, not its parent.
        ScrollViewerAbove(PanelFor(screen))?.ScrollToTop();

        await SettleAsync();
    }

    /// <inheritdoc />
    public async Task BringIntoViewAsync(object content)
    {
        ArgumentNullException.ThrowIfNull(content);

        // The rows and the forms are generated by the layout pass: let it run first.
        await SettleAsync();

        // A selection is presented twice — its row in the list and its form under it — and the
        // form is the larger of the two; a row of a plain list is presented once.
        var target = CaptureVisualTree.Descendants(Window)
            .OfType<FrameworkElement>()
            .Where(element => element is { IsVisible: true, ActualHeight: > 0 }
                           && ReferenceEquals(ContentOf(element), content))
            .MaxBy(element => element.ActualHeight)
            ?? throw new InvalidOperationException(
                $"the campaign asked to bring {content.GetType().Name} into view, and nothing on screen presents it");

        target.BringIntoView();
        await SettleAsync();
    }

    /// <summary>The scroll viewer a screen's panel scrolls in, however deep the page host nests it.</summary>
    private static ScrollViewer? ScrollViewerAbove(FrameworkElement? panel)
    {
        for (var node = panel?.Parent; node is not null; node = LogicalTreeHelper.GetParent(node))
        {
            if (node is ScrollViewer viewer)
                return viewer;
        }

        return null;
    }

    private static object? ContentOf(FrameworkElement element) => element switch
    {
        ContentPresenter presenter => presenter.Content,
        ContentControl control => control.Content,
        _ => null,
    };

    /// <summary>The panel a stop's screen should have brought forward, so the shot can be checked.</summary>
    public FrameworkElement? PanelFor(CaptureScreen screen) => screen switch
    {
        CaptureScreen.Create => Window.CreatePanel,
        CaptureScreen.Teams => Window.TeamsPanel,
        CaptureScreen.Import => Window.ImportPanel,
        CaptureScreen.Run or CaptureScreen.Test => Window.RunPanel,
        CaptureScreen.History => Window.HistoryPanel,
        CaptureScreen.Diagnostic => Window.DiagPanel,
        _ => Window.SettingsPanel,
    };

    /// <inheritdoc />
    public void ShowSplash() => Window.PoseSplashForCapture();

    /// <inheritdoc />
    public void HideSplash() => Window.HideSplashForCapture();

    /// <inheritdoc />
    public void StartTourAt(int stepIndex) => Window.Tour.Start(MainWindow.TourSteps, stepIndex);

    /// <inheritdoc />
    public void EndTour() => Window.Tour.End();

    /// <inheritdoc />
    public async Task SettleAsync() => await CaptureSettle.SettleAsync(Window);

    private void ShowSettings(ViewModels.Mvvm.RelayCommand command)
    {
        Window.NavSettings.IsChecked = true;
        command.Execute(null);
    }
}
